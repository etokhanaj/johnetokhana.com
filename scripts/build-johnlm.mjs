// Packs JohnLM's knowledge into netlify/johnlm/bundle.mjs before each build:
// the system prompt, the fact file, and the plain text of every case study.
import { readFileSync, writeFileSync, existsSync, readdirSync } from 'node:fs';

const read = (p, fallback = '') => (existsSync(p) ? readFileSync(p, 'utf8') : fallback);

const system = read('src/content/johnlm/system.md', 'You are JohnLM. Answer only from the knowledge below. If it is not there, say so and suggest emailing etokhanaj@gmail.com.');
const facts = read('src/content/johnlm/facts.md');

// Case studies as plain text: drop frontmatter and imports, keep prose and
// the alt text of figures (it describes what each screen shows).
const study = (f) => {
  let s = read(`src/content/work/${f}`);
  const fm = s.match(/^---\n([\s\S]*?)\n---\n/);
  const dek = fm ? (fm[1].match(/dek:\s*"([^"]*)"/) || [])[1] || '' : '';
  s = s.replace(/^---\n[\s\S]*?\n---\n/, '').replace(/^import .*$/gm, '');
  const alts = [...s.matchAll(/alt[=:]\s*["']([^"']+)["']/g)].map((m) => `[Screen: ${m[1]}]`);
  // Unwrap inline components like <Led>…</Led> first, or the next rule would
  // run from <Led> to the next />
  s = s.replace(/<\/?[A-Z][A-Za-z]*>/g, '');
  s = s.replace(/<[A-Z][\s\S]*?\/>/g, '').replace(/\{\/\*[\s\S]*?\*\/\}/g, '');
  return `## Case study: ${f.replace('.mdx', '')}\n${dek}\n${s.trim()}\n${alts.join('\n')}`;
};
const files = readdirSync('src/content/work').filter((f) => f.endsWith('.mdx'));

// Episode's case study has been public since 11 Nov 2026, so there is one
// version of JohnLM's knowledge. SYSTEM_PUBLIC stays as an alias so the eval
// harness, which still labels some cases public, keeps working.
const fill = (sys, f, studies) =>
  sys.includes('{{FACTS}}')
    ? sys.replace('{{FACTS}}', f).replace('{{CASE_STUDIES}}', studies)
    : `${sys}\n\n<facts>\n${f}\n</facts>\n\n<case_studies>\n${studies}\n</case_studies>`;
const full = fill(system, facts, files.map(study).join('\n\n'));
const pub = full;

const out = `// Generated by scripts/build-johnlm.mjs. Do not edit.\nexport const SYSTEM = ${JSON.stringify(full)};\nexport const SYSTEM_PUBLIC = ${JSON.stringify(pub)};\n`;
writeFileSync('netlify/johnlm/bundle.mjs', out);
console.log(`johnlm bundle: ${full.length} chars full, ${pub.length} public`);
